"""Markdown report renderer."""

from __future__ import annotations

from ..core.models import Finding, ScanReport
from .common import SEVERITY_LABEL, split_findings, summary_lines


def _metadata_table(report: ScanReport) -> list[str]:
    meta = report.metadata
    rows = [
        ("Target", meta.target),
        ("Mode", meta.mode.value),
        ("Tool version", meta.tool_version),
        ("Started", meta.started_at.isoformat()),
        ("Finished", meta.finished_at.isoformat() if meta.finished_at else "-"),
        ("Scope", ", ".join(meta.scope) or "(not restricted)"),
        ("Techniques", ", ".join(meta.techniques) or "passive"),
        ("Requests sent", str(meta.request_count)),
        ("Interrupted", "yes" if meta.interrupted else "no"),
    ]
    if meta.authorization:
        rows.extend(
            [
                ("Engagement", meta.authorization.engagement or "-"),
                ("Authorized by", meta.authorization.authorized_by or "-"),
                (
                    "Authorization valid",
                    f"{meta.authorization.valid_from} to {meta.authorization.valid_until}",
                ),
                ("Incident contact", meta.authorization.contact_for_incident or "-"),
            ]
        )
    lines = ["| Field | Value |", "| --- | --- |"]
    lines.extend(f"| {name} | {value} |" for name, value in rows)
    return lines


def _finding_block(finding: Finding) -> list[str]:
    heading = f"### [{SEVERITY_LABEL[finding.severity.value]}] {finding.title}"
    lines = [heading, ""]
    facts = [
        ("Confidence", finding.confidence.value),
        ("Evidence type", finding.evidence_type.value),
        ("Category", finding.category),
    ]
    if finding.url:
        facts.append(("URL", finding.url))
    if finding.parameter:
        facts.append(("Parameter", finding.parameter))
    if finding.source:
        facts.append(("Detected by", finding.source))
    lines.extend(f"- **{name}:** {value}" for name, value in facts)
    if finding.explanation:
        lines.extend(["", finding.explanation])
    if finding.remediation:
        lines.extend(["", f"**Remediation:** {finding.remediation}"])
    if finding.verification:
        lines.extend(["", f"**Safe manual verification:** {finding.verification}"])
    if finding.evidence:
        rendered = ", ".join(f"{key}={value}" for key, value in finding.evidence.items())
        lines.extend(["", f"**Evidence:** {rendered}"])
    lines.append("")
    return lines


def render_markdown(report: ScanReport) -> str:
    passive, active = split_findings(report.findings)
    lines: list[str] = [f"# ReconPulse report - {report.metadata.target}", ""]
    lines.extend(
        [
            "> Generated by ReconPulse for authorized security testing only.",
            "> Static findings are indicators, not confirmed vulnerabilities.",
            "",
            "## Scan metadata",
            "",
        ]
    )
    lines.extend(_metadata_table(report))
    lines.extend(["", "## Executive summary", ""])
    lines.extend(f"- {line}" for line in summary_lines(report))
    lines.append("")

    lines.extend([f"## Passive findings ({len(passive)})", ""])
    if passive:
        for finding in passive:
            lines.extend(_finding_block(finding))
    else:
        lines.extend(["No passive findings.", ""])

    if report.metadata.mode.value == "active" or active:
        lines.extend([f"## Active findings ({len(active)})", ""])
        if active:
            for finding in active:
                lines.extend(_finding_block(finding))
        else:
            lines.extend(["No active findings.", ""])

    if report.out_of_scope:
        lines.extend(["## Out-of-scope discoveries (not contacted)", ""])
        for discovery in report.out_of_scope:
            detail = f" - {discovery.detail}" if discovery.detail else ""
            lines.append(f"- `{discovery.host}` (found by {discovery.discovered_by}){detail}")
        lines.append("")

    if report.errors:
        lines.extend(["## Errors", ""])
        lines.extend(f"- {error}" for error in report.errors)
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"
